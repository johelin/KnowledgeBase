public class SnusShop {
    // use encapsulation
    // initialize name, price, brand, strength, flavor, stock
    private String name;
    private double price;
    private String brand;
    private String strenght;


    public String getName() {
        return name;
    }
    public double getPrice() {
        return price;
    }
    public String getBrand() {
        return brand;
    }

    public String getStrenght() {
        return strenght;
    }

    public void setName(String SnusName) {
        name= SnusName;
    }
    public void setPrice(double SnusPrice) {
         price=SnusPrice;
    }
    public void setBrand(String SnusBrand) {
         brand=SnusBrand;
    }

    public void setStrenght(String SnusStrenght) {
         strenght=SnusStrenght;
    }



}


